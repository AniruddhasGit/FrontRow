#!/usr/bin/env python3
"""The Render + Neon deploy kit for the always-on free copy (SRC-005 D-2). Standard library only.

    python scripts/render_deploy.py             # DRY RUN (the default): GET calls only, prints the plan, secrets masked
    python scripts/render_deploy.py --apply     # find-or-create frontrow-web and frontrow-api, set env and routes
    python scripts/render_deploy.py --deploy    # trigger ONE deploy of each existing service (combine with --apply)

What it manages, by name (idempotent: an existing service is updated, never duplicated):
  frontrow-web  Render static site: frontend/ built by vite, /api/* rewritten to the API, everything else -> index.html
  frontrow-api  Render free web service: backend/Dockerfile from the repository root (the same image as AWS)
  frontrow-redis is NOT created: it already exists (Render Key Value, Singapore); only its internal URL is read.

Secrets come from passwords.txt (default D:/Project/FrontRow/passwords.txt, or --passwords): RENDER_API_KEY,
RESEND_API_KEY and FRONTROW_NEON_APP_URL. No secret is written to this file, printed, or put in an error message.
autoDeployTrigger is "off": the owner's free-tier rule is that deploys are triggered by hand and batched.
"""

from __future__ import annotations

import argparse
import json
import sys
import urllib.error
import urllib.parse
import urllib.request
from pathlib import Path

API = "https://api.render.com/v1"
REPO, BRANCH, REGION = "https://github.com/AniruddhasGit/FrontRow", "main", "singapore"
REDIS_NAME, API_NAME, WEB_NAME = "frontrow-redis", "frontrow-api", "frontrow-web"
# Masked in every printout. The URLs keep scheme, user and host (so a dry run shows direct vs pooled), never the password.
SECRET_KEYS = {"DATABASE_URL", "REDIS_URL", "JWT_SECRET", "RESEND_SECRET", "AWS_ACCESS_KEY_ID", "AWS_SECRET_ACCESS_KEY"}

# /health/live: answers from the process alone. /health/ready queries Neon and Redis, so Render's probe would (a) spend
# Neon compute hours on every probe while the instance is up and (b) fail during a Neon cold start and mark a healthy
# deploy as failed. Liveness is what a restart decision needs (the Dockerfile HEALTHCHECK comment, SRC-002 §7.4).
HEALTH_PATH = "/health/live"


def read_passwords(path: Path) -> dict[str, str]:
    """KEY=VALUE lines only; comments, headings and `name: value` lines are skipped."""
    out = {}
    for line in path.read_text(encoding="utf-8").splitlines():
        key, sep, value = line.partition("=")
        if sep and key.strip().isidentifier():
            out[key.strip()] = value.strip()
    return out


def direct(url: str) -> str:
    """Neon's pooled host -> its direct host. The engine sends `options=-c statement_timeout=...` at connect
    (app/db/__init__.py), and Neon's PgBouncer refuses that startup parameter; the API's 5+2 connections fit easily
    inside the direct endpoint's limit, so pooling buys nothing here."""
    parts = urllib.parse.urlsplit(url)
    return parts._replace(netloc=parts.netloc.replace("-pooler.", ".", 1)).geturl()


def mask(key: str, value: str | None) -> str:
    if value is None:
        return "<generated by Render on create (generateValue)>"
    if key not in SECRET_KEYS:
        return value
    parts = urllib.parse.urlsplit(value)
    if parts.scheme and parts.hostname:
        user = f"{parts.username}:***@" if parts.username else ("***@" if parts.password else "")
        return f"{parts.scheme}://{user}{parts.hostname}{':%d' % parts.port if parts.port else ''}{parts.path}" + \
               (f"?{parts.query}" if parts.query else "")
    return f"<secret, {len(value)} chars>"


class Render:
    def __init__(self, key: str) -> None:
        self.key = key

    def call(self, method: str, path: str, body=None, query: dict | None = None):
        url = API + path + ("?" + urllib.parse.urlencode(query) if query else "")
        req = urllib.request.Request(url, method=method, data=None if body is None else json.dumps(body).encode(), headers={
            "Authorization": f"Bearer {self.key}", "Accept": "application/json", "Content-Type": "application/json",
            "User-Agent": "frontrow-render-deploy"})
        try:
            with urllib.request.urlopen(req, timeout=30) as resp:  # noqa: S310 - fixed https base
                raw = resp.read()
                return json.loads(raw) if raw else None
        except urllib.error.HTTPError as exc:
            # Render's own words, bounded. The request (and so the key) is never echoed.
            sys.exit(f"render_deploy: {method} {path} -> HTTP {exc.code}: {exc.read()[:300].decode('utf-8', 'replace')}")
        except urllib.error.URLError as exc:
            sys.exit(f"render_deploy: {method} {path} -> {exc.reason}")

    def service(self, owner: str, name: str) -> dict | None:
        rows = self.call("GET", "/services", query={"name": name, "ownerId": owner, "limit": 100}) or []
        hits = [r["service"] for r in rows if r["service"]["name"] == name]
        return hits[0] if hits else None

    def env(self, service_id: str) -> dict[str, str]:
        rows = self.call("GET", f"/services/{service_id}/env-vars", query={"limit": 100}) or []
        return {r["envVar"]["key"]: r["envVar"]["value"] for r in rows}


def api_env(pw: dict[str, str], redis_url: str, web_url: str, existing: dict[str, str]) -> dict[str, str | None]:
    """Every variable app/core/config.py requires (no default), plus the overrides the Render copy needs.
    Variables with a ruled default are left to the code: a second copy here could only drift."""
    return {
        # The application role, never the owner: least privilege, the grants in migration 0001.
        "DATABASE_URL": direct(pw["FRONTROW_NEON_APP_URL"]),
        "REDIS_URL": redis_url,
        # Required by config.py, read by nothing when MAIL_PROVIDER=resend (no queue, no worker: server.py and
        # workers.receipt_port skip it). .invalid never resolves, so an accidental use fails loudly.
        "QUEUE_URL": "http://no-queue.invalid/render-copy-has-no-queue",
        # Kept across runs: a new value signs every customer out. None -> Render generates it on first create.
        "JWT_SECRET": existing.get("JWT_SECRET"),
        "PAYMENT_PROVIDER": "simulated",
        "MAIL_PROVIDER": "resend",
        "RESEND_SECRET": pw["RESEND_API_KEY"],
        # Resend's shared sender: until a domain is verified it delivers only to the account's sign-up address.
        "SES_SENDER_ADDRESS": "FrontRow <onboarding@resend.dev>",
        # Check 15: the mail call must finish inside QUEUE_SEND_TIMEOUT_MS (2000, the default).
        "SES_SEND_TIMEOUT_MS": "1500",
        # Required by config.py. There is no bucket: poster upload and the admin poster read answer 503 (posters.py).
        # SRC-007 STORE-1: posters in Cloudflare R2 when its values are in passwords.txt (DEPLOY_RENDER.md section 6),
        # else the old no-bucket constants. No value is printed.
        **({"S3_BUCKET_NAME": pw["R2_BUCKET"], "AWS_ENDPOINT_URL_S3": pw["R2_ENDPOINT"],
            "AWS_ACCESS_KEY_ID": pw["R2_ACCESS_KEY_ID"], "AWS_SECRET_ACCESS_KEY": pw["R2_SECRET_ACCESS_KEY"],
            "AWS_REGION": "auto"}
           if all(pw.get(k) for k in ("R2_BUCKET", "R2_ENDPOINT", "R2_ACCESS_KEY_ID", "R2_SECRET_ACCESS_KEY"))
           else {"S3_BUCKET_NAME": "no-bucket-on-render", "AWS_REGION": "ap-southeast-1"}),
        # Without it boto3's credential chain probes the EC2 metadata address before giving up; with it the
        # missing-credentials 503 is immediate.
        "AWS_EC2_METADATA_DISABLED": "true",
        "PUBLIC_BASE_URL": web_url,
        "COOKIE_SECURE": "true",
        # ponytail: Render's proxy reaches the container from its private 10/8 network; the exact hop is not published.
        # Ceiling: behind the static site's rewrite the rightmost X-Forwarded-For entry may be that proxy, not the
        # browser, so IP buckets may be shared by all visitors (DEPLOY_RENDER.md, "what the free copy does not have").
        "FORWARDED_ALLOW_IPS": "10.0.0.0/8",
        "PAYMENT_SIMULATOR_FAIL_KEY_PREFIX": "simfail-",
        # The default 1 s is shorter than a Neon compute waking from autosuspend; 5 s stays inside the 10 s bound.
        "DB_CONNECT_TIMEOUT_MS": "5000",
        # Render routes to $PORT (default 10000). The image binds API_PORT, 8000 by default.
        "PORT": "8000",
    }


def env_body(env: dict[str, str | None]) -> list[dict]:
    return [{"key": k, "generateValue": True} if v is None else {"key": k, "value": v} for k, v in env.items()]


def web_details(api_url: str) -> dict:
    return {
        "buildCommand": "cd frontend && npm ci && npm run build",
        "publishPath": "frontend/dist",
        # First rule wins (PUT /routes: list order is priority). Files that exist are served before any rule.
        "routes": [
            {"type": "rewrite", "source": "/api/*", "destination": f"{api_url}/api/*"},
            {"type": "rewrite", "source": "/*", "destination": "/index.html"},
        ],
    }


WEB_ENV = {"NODE_VERSION": "24"}  # vite 8 and TypeScript 7 need a current Node; 24 is what the build was run on


def api_details() -> dict:
    return {"runtime": "docker", "plan": "free", "region": REGION, "healthCheckPath": HEALTH_PATH,
            "envSpecificDetails": {"dockerfilePath": "./backend/Dockerfile", "dockerContext": "."}}


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n\n")[0])
    ap.add_argument("--passwords", type=Path, default=Path("D:/Project/FrontRow/passwords.txt"))
    ap.add_argument("--apply", action="store_true", help="create or update the services (default: dry run)")
    ap.add_argument("--deploy", action="store_true", help="trigger one deploy of each service not created in this run")
    args = ap.parse_args(argv)

    pw = read_passwords(args.passwords)
    missing = [k for k in ("RENDER_API_KEY", "RESEND_API_KEY", "FRONTROW_NEON_APP_URL") if not pw.get(k)]
    if missing:
        sys.exit(f"render_deploy: {args.passwords} has no value for {', '.join(missing)}")
    r = Render(pw["RENDER_API_KEY"])

    kvs = [x["keyValue"] for x in r.call("GET", "/key-value", query={"name": REDIS_NAME, "limit": 100}) or []
           if x["keyValue"]["name"] == REDIS_NAME]
    if not kvs:
        sys.exit(f"render_deploy: no Key Value named {REDIS_NAME}; it is expected to exist already (SRC-005 D-2)")
    kv = kvs[0]
    owner = (kv.get("owner") or {}).get("id") or kv.get("ownerId")  # the workspace that holds the Redis holds the app
    if kv.get("region") != REGION:
        sys.exit(f"render_deploy: {REDIS_NAME} is in {kv.get('region')}, not {REGION}; its internal URL would not resolve")
    redis_url = r.call("GET", f"/key-value/{kv['id']}/connection-info")["internalConnectionString"]

    web, api = r.service(owner, WEB_NAME), r.service(owner, API_NAME)
    # ponytail: a new service's URL is predicted from its name; Render adds a suffix if that subdomain is taken, so
    # --apply always uses the URL in the create response, and a dry run before the first create may show a guess.
    web_url = web["serviceDetails"]["url"] if web else f"https://{WEB_NAME}.onrender.com"
    api_url = api["serviceDetails"]["url"] if api else f"https://{API_NAME}.onrender.com"
    env = api_env(pw, redis_url, web_url, r.env(api["id"]) if api else {})

    mode = ("APPLY" if args.apply else "DEPLOY ONLY (services unchanged; deploys are triggered)" if args.deploy
            else "DRY RUN (nothing is changed; --apply to change)")
    print(f"render_deploy: {mode}")
    print(f"  workspace   {owner}  ({(kv.get('owner') or {}).get('name', '?')})")
    print(f"  redis       {REDIS_NAME}  {kv['id']}  region={kv.get('region')}  plan={kv.get('plan')}  url={mask('REDIS_URL', redis_url)}")
    print(f"  {WEB_NAME:<14}{'UPDATE ' + web['id'] if web else 'CREATE'}  static_site  {web_url}")
    for k, v in web_details(api_url).items():
        print(f"      {k} = {json.dumps(v)}")
    print(f"      env NODE_VERSION = {WEB_ENV['NODE_VERSION']}")
    print(f"  {API_NAME:<14}{'UPDATE ' + api['id'] if api else 'CREATE'}  web_service  {api_url}")
    print(f"      repo = {REPO}@{BRANCH}  autoDeployTrigger = off")
    for k, v in api_details().items():
        print(f"      {k} = {json.dumps(v)}")
    for k, v in env.items():
        print(f"      env {k} = {mask(k, v)}")
    print(f"  deploy      {'one deploy of each service not created in this run' if args.deploy else 'none (--deploy)'}")
    if not args.apply and not args.deploy:
        return 0

    created = set()
    if args.apply:
        # Web first: the API's PUBLIC_BASE_URL is the web URL. Then the API, then the web's rewrite to the API's URL.
        common = {"ownerId": owner, "repo": REPO, "branch": BRANCH, "autoDeployTrigger": "off"}
        details = web_details(api_url)
        if not web:
            web = r.call("POST", "/services", {**common, "type": "static_site", "name": WEB_NAME, "envVars": env_body(WEB_ENV),
                                               "serviceDetails": {k: v for k, v in details.items() if k != "routes"}})["service"]
            created.add(web["id"])
        else:
            r.call("PATCH", f"/services/{web['id']}", {"autoDeployTrigger": "off", "serviceDetails": {
                "buildCommand": details["buildCommand"], "publishPath": details["publishPath"]}})
            r.call("PUT", f"/services/{web['id']}/env-vars", env_body(WEB_ENV))
        env["PUBLIC_BASE_URL"] = web["serviceDetails"]["url"]
        if not api:
            api = r.call("POST", "/services", {**common, "type": "web_service", "name": API_NAME, "envVars": env_body(env),
                                               "serviceDetails": api_details()})["service"]
            created.add(api["id"])
        else:
            r.call("PATCH", f"/services/{api['id']}", {"autoDeployTrigger": "off", "serviceDetails": {
                k: v for k, v in api_details().items() if k in ("plan", "healthCheckPath", "envSpecificDetails")}})
            r.call("PUT", f"/services/{api['id']}/env-vars", env_body(env))
        r.call("PUT", f"/services/{web['id']}/routes", web_details(api["serviceDetails"]["url"])["routes"])
        print(f"applied: {WEB_NAME} {web['serviceDetails']['url']}  {API_NAME} {api['serviceDetails']['url']}")
    if args.deploy:
        # A create already starts the first build; deploying it again would spend build minutes twice.
        for svc in (s for s in (api, web) if s and s["id"] not in created):
            d = r.call("POST", f"/services/{svc['id']}/deploys", {"clearCache": "do_not_clear"})
            print(f"deploy triggered: {svc['name']} {d.get('id') if d else ''}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
